    private static let mapping: [UInt16: UInt16] = {
        var mapping: [UInt16: UInt16] = [:]
        for run in runs {
            for codeUnit in stride(from: run.first, through: run.last, by: Int(run.stride)) {
                mapping[codeUnit] = UInt16(Int32(codeUnit) + run.delta)
            }
        }
        return mapping
    }()

    /// What Windows' RtlUpcaseUnicodeChar makes of `codeUnit`.
    static func uppercased(_ codeUnit: UInt16) -> UInt16 {
        mapping[codeUnit] ?? codeUnit
    }

    /// What Windows' RtlUpcaseUnicodeString makes of `text`, one UTF-16 code unit at a time.
    static func uppercased(_ text: String) -> String {
        String(decoding: text.utf16.map(uppercased), as: UTF16.self)
    }
